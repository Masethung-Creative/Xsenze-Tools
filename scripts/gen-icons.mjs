// Writes app/lib/icons.ts: every lucide icon the app refers to, bundled as raw
// SVG.
//   npm run gen-icons   (run after using a new icon name)
import {
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
  statSync,
} from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// names built at runtime, outside templates
const EXTRA = ['arrow-right', 'download', 'triangle-alert', 'circle-check-big'];

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const p = join(dir, entry);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const found = new Set();
for (const file of walk(join(root, 'app')).filter(
  (f) => /\.(gts|ts)$/.test(f) && !f.endsWith('icons.ts'),
)) {
  const src = readFileSync(file, 'utf8');
  const patterns = [
    /@name=["']([a-z0-9-]+)["']/g,
    /@icon=["']([a-z0-9-]+)["']/g,
    /\bicon:\s*["']([a-z0-9-]+)["']/g,
    /IconSvg\s+@?name=["']([a-z0-9-]+)["']/g,
    /'([a-z0-9]+(?:-[a-z0-9]+)*)'/g, // any quoted name; filtered to real icons below
  ];
  for (const re of patterns) for (const m of src.matchAll(re)) found.add(m[1]);
  for (const m of src.matchAll(/@name=\{\{[^}]*\}\}/g)) {
    for (const s of m[0].matchAll(/["']([a-z0-9-]+)["']/g)) found.add(s[1]);
  }
}

const isIcon = (n) =>
  existsSync(join(root, 'node_modules/lucide-static/icons', `${n}.svg`));

const names = [...new Set([...found, ...EXTRA])].filter(isIcon).sort();

const ident = (n) =>
  'i' +
  n
    .split('-')
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');
const key = (n) => (/^[a-z][a-z\d]*$/.test(n) ? n : `'${n}'`);

const out = `// generated by scripts/gen-icons.mjs; do not edit
${names.map((n) => `import ${ident(n)} from 'lucide-static/icons/${n}.svg?raw';`).join('\n')}

export const icons: Record<string, string> = {
${names.map((n) => `  ${key(n)}: ${ident(n)},`).join('\n')}
};

export type IconName = string;
`;

writeFileSync(join(root, 'app/lib/icons.ts'), out);
console.log(`wrote app/lib/icons.ts: ${names.length} icons`);
